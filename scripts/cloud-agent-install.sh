#!/usr/bin/env bash
# Idempotent Cloud Agent environment bootstrap for Autobio.
# Installs JS dependencies, builds Cloud Functions, pre-caches the Firebase
# Emulator Suite binaries, and writes a local emulator-backed web env file.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

echo "==> Installing npm workspace dependencies"
npm install

echo "==> Building Cloud Functions (required by the Functions emulator)"
npm --workspace=functions run build

echo "==> Pre-caching Firebase Emulator Suite binaries"
npx --yes firebase setup:emulators:firestore
npx --yes firebase setup:emulators:storage
npx --yes firebase setup:emulators:ui

# Local web env pointing at the Firebase Emulator Suite. No real Firebase
# credentials are needed: the emulators accept placeholder config. Developers
# who want to target the live project can overwrite this file.
env_file="apps/web/.env"
if [ ! -f "$env_file" ]; then
  echo "==> Writing $env_file (emulator-backed local config)"
  cat > "$env_file" <<'EOF'
# Local development against the Firebase Emulator Suite.
# Generated by scripts/cloud-agent-install.sh; safe to edit locally.
VITE_USE_FIREBASE_EMULATORS=true
VITE_FIREBASE_EMULATOR_HOST=127.0.0.1

# Emulators ignore the real values below, so placeholders are fine for local dev.
VITE_FIREBASE_API_KEY=demo-api-key
VITE_FIREBASE_AUTH_DOMAIN=autobio-b5dbf.firebaseapp.com
VITE_FIREBASE_PROJECT_ID=autobio-b5dbf
VITE_FIREBASE_STORAGE_BUCKET=autobio-b5dbf.firebasestorage.app
VITE_FIREBASE_MESSAGING_SENDER_ID=000000000000
VITE_FIREBASE_APP_ID=1:000000000000:web:demo
VITE_FIREBASE_MEASUREMENT_ID=
VITE_PUBLIC_APP_URL=http://localhost:5173
EOF
else
  echo "==> $env_file already exists; leaving it untouched"
fi

echo "==> Cloud Agent install complete"
